/**
 * Dev-time type generator for the read SDK (M103, ADR-1).
 *
 * Builds the live OpenAPI document from the engine's mounted routes and generates
 * TypeScript response types from it with `openapi-typescript` (a dev-dep — the emitted
 * types are erased at build, so the customer bundle is unaffected). Both the spec
 * snapshot and the generated `.d.ts` are committed so `npm install` needs no build tools.
 *
 * Run via `pnpm --filter @looptrace/sdk generate` (which rebuilds `@looptrace/core`
 * first so the DTO components the spec references are current). The drift gate
 * (`src/read/openapi-snapshot.test.ts`) fails when the committed snapshot no longer matches
 * a freshly-built doc — the signal to re-run this generator.
 *
 * Test/dev-only coupling to the engine source, same rationale as `m1-contract.test.ts`
 * importing `@looptrace/api`. Not shipped in `dist` (excluded by tsconfig).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

// Source imports (tsx resolves .js → .ts); the engine's route table + doc builder.
import { createApp } from "../../api/src/server/app.js";
import { buildOpenApiDocument } from "../../api/src/server/openapi.js";
import type { SpanRepository } from "@looptrace/core";

const here = dirname(fileURLToPath(import.meta.url));
const sdkRoot = join(here, "..");
const SNAPSHOT_VERSION = "sdk-snapshot"; // fixed so the doc is deterministic across runs

// Route mounting never invokes repo methods; `buildOpenApiDocument` reads `app.routes` only,
// so a no-op repo is sufficient to enumerate the mounted surface.
const stubRepo = new Proxy(
  {},
  { get: () => async () => null },
) as unknown as SpanRepository;

const doc = buildOpenApiDocument(createApp(stubRepo).routes, SNAPSHOT_VERSION);

const snapshotPath = join(sdkRoot, "openapi.snapshot.json");
writeFileSync(snapshotPath, `${JSON.stringify(doc, null, 2)}\n`);

// Programmatic openapi-typescript (v7): pass a MUTABLE clone — `buildOpenApiDocument` returns a
// frozen doc (M102 memoization), and the redocly bundler openapi-typescript uses mutates `components`.
const mutableDoc = JSON.parse(JSON.stringify(doc)) as Parameters<typeof openapiTS>[0];
const ast = await openapiTS(mutableDoc);
const banner =
  "/**\n * AUTO-GENERATED by scripts/generate-types.ts (openapi-typescript) — DO NOT EDIT.\n" +
  " * Regenerate with `pnpm --filter @looptrace/sdk generate` when the drift gate fails.\n */\n";
const outDir = join(sdkRoot, "src", "__generated__");
mkdirSync(outDir, { recursive: true });
const outPath = join(outDir, "openapi.ts");
writeFileSync(outPath, banner + astToString(ast));

console.log(`generated ${outPath} from ${snapshotPath}`);
