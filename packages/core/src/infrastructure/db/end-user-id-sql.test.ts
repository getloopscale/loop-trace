/**
 * M140 T1.1 — the end-user identity expression has ONE definition.
 *
 * M131 defined "who is the end user" as `coalesce(attributes->>'user.id',
 * attributes->>'gen_ai.user.id')`. It was already written TWICE inside
 * `session-repository.ts` (:107 and :112) before this milestone added a third consumer.
 * A business rule with two copies has two truths: correcting the fallback order — or adding
 * a third attribute key — would silently fix one report and leave the other stale.
 *
 * Scope is anchored on the two files that matter, NOT on a repo-wide grep (edge case EC-2):
 * a global grep also counts `dist/` (build output, regenerated by every `pnpm build`) and the
 * doc comment in `domain/observability/session.ts` that describes the FIELD. Neither is a
 * second implementation, and a criterion that can never pass teaches people to ignore it.
 */
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { PgDialect } from "drizzle-orm/pg-core";
import { describe, expect, it } from "vitest";

import { END_USER_ID_SQL } from "./repo-shared.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const EXPR = "attributes->>'user.id'";

const read = (rel: string): string => readFileSync(join(HERE, rel), "utf8");

/** Render the fragment to real SQL text — the same path Drizzle takes to reach Postgres. */
const render = (alias: "sp" | "spans"): string =>
  new PgDialect().sqlToQuery(END_USER_ID_SQL(alias)).sql;

describe("M140 — end-user identity expression", () => {
  it("is defined in repo-shared and nowhere else in production SQL", () => {
    expect(read("repo-shared.ts")).toContain(EXPR);
    expect(read("observability/session-repository.ts")).not.toContain(EXPR);
  });

  it("keeps the M131 fallback order: user.id first, gen_ai.user.id second", () => {
    // Order is the rule, not a detail — swapping it changes which id wins when a client
    // sends both, and every report that groups by user would shift silently.
    const sql = render("spans");
    expect(sql).toContain("'user.id'");
    expect(sql).toContain("'gen_ai.user.id'");
    expect(sql.indexOf("'user.id'")).toBeLessThan(sql.indexOf("'gen_ai.user.id'"));
  });

  it("accepts exactly the aliases its real call sites use", () => {
    // EC-1: the precedent DERIVED_AGENT_NAME_SQL declares "s2" | "s3" | "spans", but the SQL
    // that consumes this fragment aliases the table as `sp` (session-repository.ts:108).
    // The union is derived from the call sites; widening it to `string` would reopen the
    // injection surface that repo-shared.ts:39-40 deliberately closed.
    expect(render("sp")).toContain("sp.attributes");
    expect(render("spans")).toContain("spans.attributes");
  });
});
